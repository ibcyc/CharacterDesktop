const {contextBridge,ipcRenderer}=require('electron');
contextBridge.exposeInMainWorld('desktopAPI',{
 // The UI language, known before the page draws anything; changing it reloads the page.
 language:ipcRenderer.sendSync('desktop:language'),
 setLanguage:id=>ipcRenderer.invoke('desktop:language-set',String(id)),
 getState:()=>ipcRenderer.invoke('desktop:state'),
 extensionPages:page=>ipcRenderer.invoke('desktop:extension-pages',String(page)),
 extensionCall:(id,name,args)=>ipcRenderer.invoke('desktop:extension-call',String(id),String(name),Array.isArray(args)?args:[]),
 setStartup:enabled=>ipcRenderer.invoke('desktop:startup',enabled),
 deleteCharacter:id=>ipcRenderer.invoke('desktop:delete-character',String(id)),
 resetCharacter:id=>ipcRenderer.invoke('desktop:reset-character',String(id)),
 pickLocal:kind=>ipcRenderer.invoke('desktop:local-pick',kind==='folder'?'folder':'file'),
 addLocal:name=>ipcRenderer.invoke('desktop:local-add',String(name)),
 renameLocal:(id,name)=>ipcRenderer.invoke('desktop:local-rename',String(id),String(name)),
 openLocalFolder:id=>ipcRenderer.invoke('desktop:local-open',String(id)),
 localImage:(id,expression)=>ipcRenderer.invoke('desktop:local-image',String(id),String(expression)),
 setTuning:(id,tuning)=>ipcRenderer.invoke('desktop:tuning',String(id),tuning),
 setInteraction:(id,value)=>ipcRenderer.invoke('desktop:interaction',String(id),value),
 listSounds:()=>ipcRenderer.invoke('desktop:sounds'),
 soundData:name=>ipcRenderer.invoke('desktop:sound',String(name)),
 deleteSound:name=>ipcRenderer.invoke('desktop:sound-delete',String(name)),
 openSounds:()=>ipcRenderer.invoke('desktop:sounds-open'),
 setVolume:value=>ipcRenderer.invoke('desktop:volume',Number(value)),
 resetAll:()=>ipcRenderer.invoke('desktop:reset-all'),
 setUi:change=>ipcRenderer.invoke('desktop:ui',{transparency:Number(change?.transparency),blur:change?.blur===undefined?undefined:!!change.blur}),
 windowAction:action=>ipcRenderer.invoke('desktop:window',String(action)),
 resetUi:()=>ipcRenderer.invoke('desktop:reset-ui'),
 shortcut:create=>ipcRenderer.invoke('desktop:shortcut',create===true),
 uninstall:options=>ipcRenderer.invoke('desktop:uninstall',{keepData:options?.keepData===true}),
 pin:(id,pinned)=>ipcRenderer.invoke('desktop:pin',String(id),pinned),
 createGroup:(name,ids)=>ipcRenderer.invoke('desktop:group-create',String(name),ids.map(String)),
 openGroup:id=>ipcRenderer.invoke('desktop:group-open',String(id)),
 deleteGroup:id=>ipcRenderer.invoke('desktop:group-delete',String(id)),
 editGroup:id=>ipcRenderer.invoke('desktop:group-edit',String(id)),
 leaveGroup:id=>ipcRenderer.invoke('desktop:group-leave',String(id)),
 saveGroup:()=>ipcRenderer.invoke('desktop:group-save'),
 cancelGroupEdit:()=>ipcRenderer.invoke('desktop:group-cancel'),
 onAsk:callback=>ipcRenderer.on('desktop:ask',(_,question)=>callback(question)),
 answer:(id,answer)=>ipcRenderer.invoke('desktop:answer',id,answer),
 resetCharacters:()=>ipcRenderer.invoke('desktop:reset-characters'),
 exportPack:()=>ipcRenderer.invoke('desktop:pack-export'),
 pendingPicture:()=>ipcRenderer.invoke('desktop:local-pending-picture'),
 addPicture:(name,data,characterId)=>ipcRenderer.invoke('desktop:add-picture',String(name),data,characterId?String(characterId):''),
 saveFile:(name,data)=>ipcRenderer.invoke('desktop:save-file',String(name),data),
 importPack:()=>ipcRenderer.invoke('desktop:pack-import'),
 relaunch:()=>ipcRenderer.invoke('desktop:relaunch'),
 quit:()=>ipcRenderer.invoke('desktop:quit'),
 setSelection:value=>ipcRenderer.invoke('desktop:selection',value),
 setMirror:(id,mirror)=>ipcRenderer.invoke('desktop:mirror',String(id),!!mirror),
 setCharacterOptions:(id,options)=>ipcRenderer.invoke('desktop:character-options',String(id),options),
 rememberExpression:(id,expression)=>ipcRenderer.invoke('desktop:remember-expression',String(id),String(expression)),
 setOptions:value=>ipcRenderer.invoke('desktop:options',value),
 setLayers:order=>ipcRenderer.invoke('desktop:layers',order),
 setLayerLock:(id,locked)=>ipcRenderer.invoke('desktop:layer-lock',String(id),!!locked),
 closeLayer:id=>ipcRenderer.invoke('desktop:layer-close',String(id)),
 getUsage:()=>ipcRenderer.invoke('desktop:usage'),
 download:url=>ipcRenderer.invoke('desktop:download',url),
 cancelDownload:()=>ipcRenderer.invoke('desktop:cancel-download'),
 openSettings:()=>ipcRenderer.send('desktop:open-settings'),
 hit:(value,moved)=>ipcRenderer.send('desktop:hit',!!value,!!moved), say:(text,point)=>ipcRenderer.send('desktop:say',String(text),point), bubbleStage:id=>ipcRenderer.invoke('desktop:bubble-stage',String(id)),
 dragStart:(x,y)=>ipcRenderer.send('desktop:drag-start',x,y),
 dragTo:(x,y)=>ipcRenderer.send('desktop:drag-to',x,y),
 dragEnd:()=>ipcRenderer.send('desktop:drag-end'),
 petReady:()=>ipcRenderer.send('desktop:pet-ready'),
 petError:message=>ipcRenderer.send('desktop:pet-error',String(message)),
 onCursor:callback=>{const listener=(_,data)=>callback(data);ipcRenderer.on('desktop:cursor',listener);return ()=>ipcRenderer.removeListener('desktop:cursor',listener);},
 onCharacter:callback=>{const listener=(_,data)=>callback(data);ipcRenderer.on('desktop:character',listener);return ()=>ipcRenderer.removeListener('desktop:character',listener);},
 onOptions:callback=>{const listener=(_,data)=>callback(data);ipcRenderer.on('desktop:options',listener);return ()=>ipcRenderer.removeListener('desktop:options',listener);},
 onEditCharacter:callback=>{const listener=(_,id)=>callback(id);ipcRenderer.on('desktop:edit-character',listener);return ()=>ipcRenderer.removeListener('desktop:edit-character',listener);},
 onDownloadProgress:callback=>{const listener=(_,data)=>callback(data);ipcRenderer.on('desktop:download-progress',listener);return ()=>ipcRenderer.removeListener('desktop:download-progress',listener);}
});
